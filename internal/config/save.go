package config

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"strings"

	"github.com/BurntSushi/toml"
)

// Save атомарно пишет весь config.toml. Комментарии и ручное форматирование
// при этом теряются — для точечной смены темы есть SaveTheme.
func Save(c Config) error {
	path, err := ConfigPath()
	if err != nil {
		return fmt.Errorf("config: %w", err)
	}
	data, err := toml.Marshal(c)
	if err != nil {
		return fmt.Errorf("config: %w", err)
	}
	body := append([]byte("# generated by pero\n"), data...)
	if err := writeAtomic(path, body, 0o644); err != nil {
		return fmt.Errorf("config: %w", err)
	}
	return nil
}

// SaveTheme меняет только строку theme = "...", не разбирая и не переписывая
// остальной файл. Если файла нет, он создаётся из DefaultTOML.
func SaveTheme(name string) error {
	name = strings.ToLower(strings.TrimSpace(name))
	if !knownTheme(name) {
		name = "plain"
	}
	path, err := ConfigPath()
	if err != nil {
		return fmt.Errorf("config: %w", err)
	}
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		data = []byte(DefaultTOML)
	} else if err != nil {
		return fmt.Errorf("config: %s: %w", path, err)
	}
	if err := writeAtomic(path, []byte(setThemeLine(string(data), name)), 0o644); err != nil {
		return fmt.Errorf("config: %w", err)
	}
	return nil
}

// setThemeLine заменяет top-level theme или вставляет его после шапки-комментариев.
func setThemeLine(text, name string) string {
	value := fmt.Sprintf("theme = %q", name)
	if text == "" {
		return value + "\n"
	}
	lines := strings.Split(text, "\n")
	inTable := false
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") {
			inTable = true
		}
		if inTable {
			continue
		}
		key, _, ok := strings.Cut(trimmed, "=")
		if !ok || strings.TrimSpace(key) != "theme" {
			continue
		}
		indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
		eol := ""
		if strings.HasSuffix(line, "\r") {
			eol = "\r"
		}
		lines[i] = indent + value + eol
		return strings.Join(lines, "\n")
	}

	at := 0
	for at < len(lines) {
		trimmed := strings.TrimSpace(lines[at])
		if trimmed != "" && !strings.HasPrefix(trimmed, "#") {
			break
		}
		at++
	}
	out := make([]string, 0, len(lines)+1)
	out = append(out, lines[:at]...)
	out = append(out, value)
	out = append(out, lines[at:]...)
	return strings.Join(out, "\n")
}
