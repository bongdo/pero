func TestSaveThemeBrokenTOML(t *testing.T) {
	cfgPath, _ := testEnv(t)
	writeFile(t, cfgPath, "theme = \"nord\"\nbroken = [\n")

	if err := SaveTheme("monokai"); err != nil {
		t.Fatalf("SaveTheme не должен разбирать TOML: %v", err)
	}
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	got := string(data)
	if !strings.Contains(got, `theme = "monokai"`) {
		t.Errorf("тема не заменилась:\n%s", got)
	}
	if !strings.Contains(got, "broken = [") {
		t.Errorf("битая строка потерялась:\n%s", got)
	}

	// Неизвестное имя не должно попасть в конфиг: загрузка всё равно даст plain.
	if err := SaveTheme("no-such-theme"); err != nil {
		t.Fatalf("SaveTheme unknown: %v", err)
	}
	data, err = os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), `theme = "plain"`) {
		t.Errorf("неизвестная тема должна стать plain:\n%s", data)
	}
}

func TestSaveThemeInsertsAfterComments(t *testing.T) {
	cfgPath, _ := testEnv(t)
	writeFile(t, cfgPath, "# шапка\n\n[editor]\ntabsize = 8\n")

	if err := SaveTheme("nord"); err != nil {
		t.Fatalf("SaveTheme: %v", err)
	}
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	got := string(data)
	themeAt := strings.Index(got, `theme = "nord"`)
	headerAt := strings.Index(got, "# шапка")
	editorAt := strings.Index(got, "[editor]")
	if themeAt < 0 || headerAt < 0 || editorAt < 0 || !(themeAt > headerAt && themeAt < editorAt) {
		t.Errorf("theme должен быть после шапки и до [editor]:\n%s", got)
	}
	if !strings.Contains(got, "tabsize = 8") {
		t.Errorf("настройки потерялись:\n%s", got)
	}

	// Повторное сохранение заменяет строку, а не добавляет вторую.
	if err := SaveTheme("plain"); err != nil {
		t.Fatalf("повторный SaveTheme: %v", err)
	}
	data, err = os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	if n := strings.Count(string(data), "theme ="); n != 1 {
		t.Errorf("theme встречается %d раз:\n%s", n, data)
	}
	if !strings.Contains(string(data), `theme = "plain"`) {
		t.Errorf("тема не заменилась:\n%s", data)
	}
}

func TestSaveRoundTrip(t *testing.T) {
	cfgPath, _ := testEnv(t)
	want := Default()
	want.Theme = "catppuccin-latte"
	want.Language = "ru"
	want.Editor.Tabsize = 2
	want.Editor.AutoPairs = false
	want.Editor.TrimTrailingWhitespace = true
	want.Editor.FinalNewline = false
	want.LSP.Servers = map[string]string{"go": "gopls", "python": "pyright-langserver --stdio"}
	want.Ignore.Dirs = []string{".git", "node_modules"}
	want.Keys = map[string]string{"Alt-t": "markdown.checkbox", "Alt-.": "lsp.codeaction"}
	want.Files = map[string]string{"*.md": "code", "*.go": "prose"}

	if err := Save(want); err != nil {
		t.Fatalf("Save: %v", err)
	}
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(data), "# generated by pero\n") {
		t.Errorf("нет заголовка Save:\n%s", data)
	}
	assertMode(t, cfgPath, 0o644)

	got, err := Load()
	if err != nil {
		t.Fatalf("Load после Save: %v", err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("round-trip разошёлся:\n got %+v\nwant %+v", got, want)
	}
}

