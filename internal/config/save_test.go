func TestSaveThemePreservesRest(t *testing.T) {
	cfgPath, _ := testEnv(t)
	body := "# мой конфиг\n" +
		"theme = \"everforest\"\n" +
		"language = \"ru\"\n\n" +
		"[editor]\n" +
		"tabsize = 2\n\n" +
		"[keys]\n" +
		"\"Alt-t\" = \"markdown.checkbox\"\n"
	writeFile(t, cfgPath, body)

	if err := SaveTheme("dracula"); err != nil {
		t.Fatalf("SaveTheme: %v", err)
	}
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	got := string(data)
	for _, want := range []string{
		"# мой конфиг", `theme = "dracula"`, `language = "ru"`,
		"[editor]", "tabsize = 2", "[keys]", `"Alt-t" = "markdown.checkbox"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("после SaveTheme потерялось %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "everforest") {
		t.Errorf("старая тема осталась:\n%s", got)
	}
	if n := strings.Count(got, "theme ="); n != 1 {
		t.Errorf("theme встречается %d раз:\n%s", n, got)
	}
	assertMode(t, cfgPath, 0o644)

	entries, err := os.ReadDir(filepath.Dir(cfgPath))
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 || entries[0].Name() != "config.toml" {
		t.Fatalf("лишние файлы после SaveTheme: %v", entries)
	}
}

